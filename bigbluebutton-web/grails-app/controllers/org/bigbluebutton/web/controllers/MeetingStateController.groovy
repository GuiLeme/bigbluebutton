package org.bigbluebutton.web.controllers

import groovy.json.JsonOutput
import groovy.json.JsonSlurper
import org.apache.commons.io.FileUtils
import org.apache.commons.lang3.StringUtils
import org.bigbluebutton.api.MeetingService
import org.bigbluebutton.api.domain.Meeting
import org.bigbluebutton.api.domain.User
import org.bigbluebutton.api.domain.UserSession
import org.bigbluebutton.api.ParamsProcessorUtil
import org.bigbluebutton.api.roomstate.RoomStateException
import org.bigbluebutton.api.roomstate.RoomStateRecordingService
import org.bigbluebutton.api.roomstate.RoomStateRestoreService
import org.bigbluebutton.api.service.DownloadResult
import org.bigbluebutton.api.util.RequestRateLimiter
import org.bigbluebutton.presentation.PresentationUrlDownloadService
import org.bigbluebutton.presentation.UploadedPresentation
import org.bigbluebutton.web.services.PresentationService

import java.nio.file.Files
import java.util.concurrent.ConcurrentHashMap
import java.util.regex.Pattern

/**
 * Saving and loading the state of a room: chat, presentations, annotations,
 * shared notes and layout. A moderator saves the state of the meeting on the
 * server (the archive is built by bbb-export-annotations), and loads a state
 * into the meeting: the one saved in it, one saved in an earlier meeting and
 * published with its recording, or an archive given as a file or a URL.
 */
class MeetingStateController {
  MeetingService meetingService
  PresentationService presentationService
  PresentationUrlDownloadService presDownloadService
  RoomStateRestoreService roomStateRestoreService
  RoomStateRecordingService roomStateRecordingService
  ParamsProcessorUtil paramsProcessorUtil
  RequestRateLimiter roomStateLoadRateLimiter

  // Meetings with a load in progress: a load replaces the content of the room,
  // two of them at once would mix their content.
  private static final Set<String> MEETINGS_LOADING = ConcurrentHashMap.newKeySet()
  private static final int MAX_URL_LENGTH = 2048

  static final String FEATURE_NAME = "roomState"
  static final String STATE_DIRECTORY = "room-state"
  static final String READY_MARKER = "ready"
  static final String ERROR_MARKER = "error.json"

  // Ids are generated by the client and become part of a file path.
  private static final Pattern JOB_ID_PATTERN = Pattern.compile('^[A-Za-z0-9]{16,64}$')

  private UserSession validateSession() {
    def sessionToken = params.sessionToken
    if (!sessionToken) return null
    UserSession userSession = meetingService.getUserSessionWithSessionToken(sessionToken)
    Boolean allowRequestsWithoutSession = meetingService.getAllowRequestsWithoutSession(sessionToken)
    if (userSession == null || (!session[sessionToken] && !allowRequestsWithoutSession)) return null
    return userSession
  }

  /**
   * Returns the meeting of a moderator's session, or null after having set the
   * response status when the request is not allowed. The moderator's user id
   * is left in the request attribute "roomStateUserId".
   */
  private Meeting authorizeModerator() {
    UserSession userSession = validateSession()
    if (userSession == null) { response.setStatus(401); return null }
    request.setAttribute("roomStateUserId", userSession.internalUserId)

    Meeting meeting = meetingService.getMeeting(userSession.meetingID)
    if (meeting == null) { response.setStatus(404); return null }

    // The role in the meeting can change after joining: trust the live user, not the session.
    User user = meeting.getUserById(userSession.internalUserId)
    if (user == null || !user.isModerator() || meeting.getDisabledFeatures().contains(FEATURE_NAME)) {
      response.setStatus(403)
      return null
    }

    return meeting
  }

  private File stateDirectory(Meeting meeting) {
    String meetingId = meeting.getInternalId()
    return new File(presentationService.roomDirectory(meetingId, meetingId), STATE_DIRECTORY)
  }

  private File saveJobDirectory(Meeting meeting) {
    String jobId = params.jobId
    if (jobId == null || !JOB_ID_PATTERN.matcher(jobId).matches()) return null

    return new File(stateDirectory(meeting), jobId)
  }

  private void renderJson(Map body) {
    response.addHeader("Cache-Control", "no-cache")
    render(text: JsonOutput.toJson(body), contentType: "application/json", encoding: "UTF-8")
  }

  def saveStatus = {
    Meeting meeting = authorizeModerator()
    if (meeting == null) return

    File jobDirectory = saveJobDirectory(meeting)
    if (jobDirectory == null) { response.setStatus(400); return }

    if (new File(jobDirectory, READY_MARKER).isFile()) {
      renderJson([status: "ready"])
    } else if (new File(jobDirectory, ERROR_MARKER).isFile()) {
      renderJson([status: "error"])
    } else {
      renderJson([status: "pending"])
    }
  }

  /**
   * The archive of a save job the moderator asked to download (see the worker
   * of bbb-export-annotations). It is built for this one download and removed
   * once sent; the state saved in the meeting is another file.
   */
  def saveDownload = {
    Meeting meeting = authorizeModerator()
    if (meeting == null) return

    File jobDirectory = saveJobDirectory(meeting)
    if (jobDirectory == null) { response.setStatus(400); return }

    File archive = new File(jobDirectory, RoomStateRecordingService.ARCHIVE_NAME)
    if (!new File(jobDirectory, READY_MARKER).isFile() || !archive.isFile()) { response.setStatus(404); return }

    if (sendArchive(archive, "room-state-" + meeting.getInternalId() + ".zip")) {
      FileUtils.deleteQuietly(archive)
    }
  }

  // Returns false when the archive could not be sent whole.
  private boolean sendArchive(File archive, String filename) {
    response.contentType = "application/zip"
    response.setContentLengthLong(archive.length())
    response.addHeader("content-disposition", "attachment; filename=\"" + filename + "\"")
    response.addHeader("Cache-Control", "no-cache")
    try {
      Files.copy(archive.toPath(), response.outputStream)
      response.outputStream.flush()
      return true
    } catch (IOException e) {
      log.error("Error sending the room state archive ${archive}: " + e.getMessage())
      return false
    }
  }

  private void renderLoadError(int status, String messageKey) {
    response.setStatus(status)
    renderJson([status: "error", messageKey: messageKey])
  }

  def loadUpload = {
    Meeting meeting = authorizeModerator()
    if (meeting == null) return

    def upload = request.respondsTo("getFile") ? request.getFile("file") : null
    if (upload == null || upload.isEmpty()) { renderLoadError(400, "invalid"); return }
    if (upload.getSize() > roomStateRestoreService.getMaxZipSize()) { renderLoadError(413, "tooLarge"); return }

    load(meeting) { File archive ->
      upload.transferTo(archive)
      return archive
    }
  }

  def loadUrl = {
    Meeting meeting = authorizeModerator()
    if (meeting == null) return

    String url = params.url
    if (!url || url.length() > MAX_URL_LENGTH) { renderLoadError(400, "invalidUrl"); return }

    load(meeting) { File archive ->
      // Same checks as a presentation given by URL: allowed protocols and hosts, no local
      // addresses, redirects followed with the same checks, download capped in size.
      DownloadResult result = presDownloadService.savePresentation(
          meeting.getInternalId(), archive.getAbsolutePath(), url, roomStateRestoreService.getMaxZipSize())
      if (result == DownloadResult.TOO_LARGE) {
        throw new RoomStateException("tooLarge", "archive at the given URL is too large")
      } else if (result != DownloadResult.SUCCESS) {
        throw new RoomStateException("downloadFailed", "could not download the archive from the given URL")
      }
      return archive
    }
  }

  // The states the moderator can load without providing an archive.
  def savedStates = {
    Meeting meeting = authorizeModerator()
    if (meeting == null) return

    renderJson([states: roomStateRecordingService.list(meeting).collect {
      [id: it.id, name: it.name, savedAt: it.savedAt]
    }])
  }

  def loadSaved = {
    Meeting meeting = authorizeModerator()
    if (meeting == null) return

    // Only the state saved in this meeting, or one the meeting was created with.
    File saved = roomStateRecordingService.archiveOf(meeting, params.state)
    if (saved == null) { renderLoadError(404, "notFound"); return }

    load(meeting) { File archive -> saved }
  }

  /**
   * API call for the front-end: the room state published with a recording
   * (the "state" format getRecordings lists), as an archive.
   */
  def getRoomState = {
    String API_CALL = "getRoomState"

    if (StringUtils.isEmpty(params.checksum)
        || !paramsProcessorUtil.isChecksumSame(API_CALL, params.checksum, request.getQueryString())) {
      response.setStatus(401)
      renderJson([returncode: "FAILED", messageKey: "checksumError", message: "You did not pass the checksum security check"])
      return
    }

    File archive = roomStateRecordingService.publishedArchive(StringUtils.strip(params.recordID))
    if (archive == null) {
      response.setStatus(404)
      renderJson([returncode: "FAILED", messageKey: "notFound", message: "No room state is published for this recordID"])
      return
    }

    sendArchive(archive, "room-state-" + archive.getParentFile().getName() + ".zip")
  }

  /**
   * Loads an archive into the meeting, replacing its presentations, chat, shared
   * notes and layout. The closure returns the archive: one it fetched into the
   * given file, which is deleted afterwards, or a saved one, which is left alone.
   */
  private void load(Meeting meeting, Closure fetchArchive) {
    String meetingId = meeting.getInternalId()
    String userId = request.getAttribute("roomStateUserId")
    String loadId = params.loadId
    if (loadId == null || !JOB_ID_PATTERN.matcher(loadId).matches()) { renderLoadError(400, "invalid"); return }

    if (!roomStateLoadRateLimiter.allow(meetingId, System.currentTimeMillis())) { renderLoadError(429, "busy"); return }
    if (!MEETINGS_LOADING.add(meetingId)) { renderLoadError(409, "busy"); return }

    File directory = new File(stateDirectory(meeting), "load-" + loadId)
    try {
      if (!directory.mkdirs()) { renderLoadError(409, "busy"); return }
      File archive = fetchArchive(new File(directory, "upload.zip"))

      RoomStateRestoreService.Result result = roomStateRestoreService.restore(archive, meetingId, userId, loadId)
      boolean presentationsEnabled = !meetingService.isMeetingWithDisabledPresentation(meetingId)
      result.presentations.each { RoomStateRestoreService.RestoredPresentation restored ->
        if (presentationsEnabled) {
          convert(meetingId, restored)
        } else {
          FileUtils.deleteQuietly(restored.file.getParentFile())
        }
      }

      renderJson([status: "loaded", client: new JsonSlurper().parseText(result.clientLayoutJson)])
    } catch (RoomStateException e) {
      log.warn("Room state not loaded into meeting ${meetingId}: ${e.getMessage()}")
      renderLoadError(422, e.getKey())
    } catch (Exception e) {
      log.error("Error loading room state into meeting ${meetingId}", e)
      renderLoadError(500, "failed")
    } finally {
      FileUtils.deleteQuietly(directory)
      MEETINGS_LOADING.remove(meetingId)
    }
  }

  // Hands a presentation of the archive to the usual conversion, as a document
  // inserted through the API would be.
  private void convert(String meetingId, RoomStateRestoreService.RestoredPresentation restored) {
    UploadedPresentation uploadedPres = new UploadedPresentation(
        "DEFAULT_PRESENTATION_POD",
        meetingId,
        restored.presentationId,
        restored.name,
        presentationService.presentationBaseUrl,
        restored.current,
        "room-state-authz-token",
        false,
        new ArrayList<String>(),
        false
    )
    uploadedPres.setUploadedFile(restored.file)
    uploadedPres.setRemovable(restored.removable)
    if (restored.downloadable) uploadedPres.setDownloadable()
    // The presentations of one archive arrive together: do not count them
    // against the limits meant for uploads made one by one.
    uploadedPres.setSystemUpload(true)
    presentationService.processUploadedPresentation(uploadedPres)
  }
}
